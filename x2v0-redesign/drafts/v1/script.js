(function () {
  var root = document.documentElement;

  function store(key, value) {
    try {
      if (value === undefined) return localStorage.getItem(key);
      localStorage.setItem(key, value);
    } catch (e) { return null; }
  }

  // Language: #en / #ru in the link wins, then the saved choice, then the browser language.
  function pickLang() {
    var h = location.hash.slice(1);
    if (h === 'en' || h === 'ru') return h;
    var saved = store('lang');
    if (saved === 'en' || saved === 'ru') return saved;
    return /^ru|^uk|^be|^kk/i.test(navigator.language || '') ? 'ru' : 'en';
  }
  function setLang(lang, save) {
    root.setAttribute('data-lang', lang);
    root.lang = lang;
    document.title = lang === 'ru'
      ? 'Валерий Онучин — инженер-программист'
      : 'Valeriy Onuchin — Software Engineer';
    var buttons = document.querySelectorAll('[data-set-lang]');
    for (var i = 0; i < buttons.length; i++) {
      buttons[i].setAttribute('aria-pressed', String(buttons[i].getAttribute('data-set-lang') === lang));
    }
    var search = document.getElementById('pub-search');
    if (search) search.placeholder = search.getAttribute('data-ph-' + lang);
    if (save) store('lang', lang);
    renderPubs();
  }

  // Theme: follows the system until the visitor picks one.
  function setTheme(theme) {
    if (theme) root.setAttribute('data-theme', theme);
    else root.removeAttribute('data-theme');
  }
  function currentTheme() {
    return root.getAttribute('data-theme') ||
      (matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
  }

  function toast(text) {
    var t = document.createElement('div');
    t.className = 'toast';
    t.setAttribute('role', 'status');
    t.textContent = text;
    document.body.appendChild(t);
    setTimeout(function () { t.remove(); }, 1800);
  }

  // Publications from ORCID (data/publications.json, generated by tools/orcid_to_json.py).
  var pubs = null;
  function renderPubs() {
    var list = document.getElementById('pubs-list');
    var count = document.getElementById('pubs-count');
    var search = document.getElementById('pub-search');
    if (!list || !pubs) return;
    var lang = root.getAttribute('data-lang') || 'ru';
    var q = (search && search.value || '').trim().toLowerCase();
    var shown = pubs.filter(function (p) {
      return !q || (p.t + ' ' + p.j + ' ' + p.y).toLowerCase().indexOf(q) !== -1;
    });
    list.textContent = '';
    shown.forEach(function (p) {
      var li = document.createElement('li');
      var yr = document.createElement('span');
      yr.className = 'yr';
      yr.textContent = p.y;
      var body = document.createElement('span');
      body.textContent = p.t;
      if (p.j) {
        var jr = document.createElement('span');
        jr.className = 'jr';
        jr.textContent = p.j;
        body.appendChild(jr);
      }
      li.appendChild(yr);
      li.appendChild(body);
      if (p.doi) {
        var a = document.createElement('a');
        a.href = 'https://doi.org/' + p.doi;
        a.target = '_blank';
        a.rel = 'noopener';
        a.textContent = 'DOI ↗';
        li.appendChild(a);
      } else {
        li.appendChild(document.createElement('span'));
      }
      list.appendChild(li);
    });
    if (count) {
      count.textContent = lang === 'ru'
        ? 'Показано ' + shown.length + ' из ' + pubs.length
        : 'Showing ' + shown.length + ' of ' + pubs.length;
    }
  }

  document.addEventListener('DOMContentLoaded', function () {
    setLang(pickLang(), false);

    document.addEventListener('click', function (e) {
      var langBtn = e.target.closest('[data-set-lang]');
      if (langBtn) setLang(langBtn.getAttribute('data-set-lang'), true);

      var themeBtn = e.target.closest('#theme-toggle');
      if (themeBtn) {
        var next = currentTheme() === 'dark' ? 'light' : 'dark';
        setTheme(next);
        store('theme', next);
      }

      var copyBtn = e.target.closest('[data-copy]');
      if (copyBtn) {
        var text = copyBtn.getAttribute('data-copy');
        var ru = root.getAttribute('data-lang') === 'ru';
        var done = function () { toast(ru ? 'Адрес скопирован' : 'Address copied'); };
        var fallback = function () {
          var out = document.getElementById('email-text');
          var range = document.createRange();
          range.selectNodeContents(out);
          var sel = getSelection();
          sel.removeAllRanges();
          sel.addRange(range);
          toast(ru ? 'Адрес выделен — нажмите Ctrl+C' : 'Address selected — press Ctrl+C');
        };
        try {
          navigator.clipboard.writeText(text).then(done, fallback);
        } catch (err) { fallback(); }
      }

      var pdfBtn = e.target.closest('#pdf-btn');
      if (pdfBtn) window.print();
    });

    window.addEventListener('hashchange', function () {
      var h = location.hash.slice(1);
      if (h === 'en' || h === 'ru') setLang(h, true);
    });

    // Printing needs a top-level page; inside a frame the button would do nothing.
    var pdfBtn = document.getElementById('pdf-btn');
    var framed = window.self !== window.top;
    if (pdfBtn && !framed) pdfBtn.hidden = false;
    // The review copy runs inside a frame; label it as a draft there.
    var note = document.getElementById('draft-note');
    if (note && framed) note.hidden = false;

    var search = document.getElementById('pub-search');
    if (search) search.addEventListener('input', renderPubs);

    fetch('data/publications.json')
      .then(function (r) { return r.json(); })
      .then(function (data) { pubs = data; renderPubs(); })
      .catch(function () {
        var list = document.getElementById('pubs-list');
        if (list) list.innerHTML = '<li><span></span><span><a href="https://orcid.org/0009-0000-3022-3529" target="_blank" rel="noopener">ORCID ↗</a></span><span></span></li>';
      });
  });

  // Apply the saved theme and language before first paint.
  var savedTheme = store('theme');
  if (savedTheme === 'dark' || savedTheme === 'light') setTheme(savedTheme);
  root.setAttribute('data-lang', pickLang());
})();
